var allLevels = { easy: easy, medium: medium, hard: hard };
var titles = { easy: "Easy", medium: "Medium", hard: "Hard" };
var units = { easy: "Sentence", medium: "Paragraph", hard: "Story" };

var level = "easy";   // the level you picked
var items = [];       // the list for that level
var index = 0;        // which item you are on (0 = the first)

// Runs when you click Easy / Medium / Hard
function startLevel(chosen) {
    level = chosen;
    items = allLevels[level];
    index = 0;

    document.getElementById("level-title").textContent = titles[level];
    document.getElementById("read-card").className = "read-card " + level;

    document.getElementById("intro").hidden = true;
    document.getElementById("practice").hidden = false;

    showItem();
}

// Runs when you click "Change level"
function goBack() {
    document.getElementById("practice").hidden = true;
    document.getElementById("intro").hidden = false;
}

// Runs when you click Previous (-1) or Next (+1)
function changeItem(step) {
    index = index + step;
    showItem();
}

// Puts the current sentence / paragraph / story on the page
function showItem() {
    var item = items[index];

    document.getElementById("persian").textContent = item.persian;
    document.getElementById("pron").textContent = item.pron;
    document.getElementById("english").textContent = item.english;

    document.getElementById("counter").textContent =
        units[level] + " " + (index + 1) + " of " + items.length;

    document.getElementById("prev").disabled = (index === 0);
    document.getElementById("next").disabled = (index === items.length - 1);

    showHide();
}

// Shows or hides the pronunciation and English based on the checkboxes
function showHide() {
    document.getElementById("pron").hidden = !document.getElementById("show-pron").checked;
    document.getElementById("english").hidden = !document.getElementById("show-eng").checked;
}
